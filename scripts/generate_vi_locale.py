def auto_translate(text: str) -> str:
    res = text
    for pat, rep in PHRASE_MAP:
        res = re.sub(pat, rep, res, flags=re.IGNORECASE)
    return res

# Build the complete vi dictionary
vi = {}
for k, v in en.items():
    if k in exact:
        vi[k] = exact[k]
    else:
        # Check if text is plain or needs phrase translation
        vi[k] = auto_translate(v)

print(f"Generated Vietnamese translation with {len(vi)} keys.")

